
class Largest {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        if (a > b) {
            System.out.println("Largest number = " + a);
        } else if (b > a) {
            System.out.println("Largest number = " + b);
        } else {
            System.out.println("Both numbers are equal");
        }
    }
}
